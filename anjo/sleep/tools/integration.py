"""The integration index, ``anjo/sleep/INTEGRATION.md`` (spec §12.4 step 2).

For every file outside the published folders that the branch changed, the index shows the
+/- counts, the added lines only, the commit subjects that added them, and for each hunk
the one ``def``/``class`` (or ``function``) line it sits in, labeled ``existing:``, without
its body. Removed lines, context lines and any other pre-existing text never appear, so
publishing the index publishes no private code beyond those signature lines.

The output depends only on the repo's commits, so regenerating it with nothing new changes
nothing and needs no commit.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from anjo.sleep.tools import _git, boundary

INDEX_PATH = "anjo/sleep/INTEGRATION.md"

_HUNK_HEADER = re.compile(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,\d+)? @@")
_SIGNATURE = re.compile(
    r"^\s*(?:export\s+)?(?:default\s+)?(?:async\s+)?(?:def|class|function)\b"
)
_BLAME_HEADER = re.compile(r"^([0-9a-f]{40}) \d+ \d+(?: \d+)?$")
_DIFF = ("diff", "-U0", "--no-renames", "--no-ext-diff", "--no-textconv", "--no-color")

_INTRO = """# Integration index

Generated by `anjo/sleep/tools/publish.py` on every publish. Do not edit it by hand.

The hackathon code lives in this repository. Small hooks ("glue") connect it to the private
Anjo app, and this page lists each one: every file outside the published folders that the
hackathon changed, with its added lines only. Removed lines are counted but never shown. A
line marked `existing:` is the signature of the function or class a hook sits in. That code
predates the hackathon, and its body stays private.
"""

_NOTHING = "No changes outside the published folders yet.\n"


@dataclass(frozen=True)
class Hunk:
    start: int  # line number of the first added line in HEAD's version, 1-based
    added: tuple[str, ...]


def _hunks(repo: Path, since: str, path: str) -> list[Hunk]:
    raw = _git.run(repo, *_DIFF, since, "HEAD", "--", path).decode("utf-8", "replace")
    hunks: list[Hunk] = []
    lines: list[str] = []
    start, in_hunk = 0, False
    for line in raw.split("\n"):
        header = _HUNK_HEADER.match(line)
        if header:
            if lines:
                hunks.append(Hunk(start, tuple(lines)))
            start, lines, in_hunk = int(header.group(1)), [], True
        elif in_hunk and line.startswith("+"):
            lines.append(line[1:])
    if lines:
        hunks.append(Hunk(start, tuple(lines)))
    return hunks


def _indent(line: str) -> int:
    return len(line) - len(line.lstrip())


def _enclosing_signature(head_lines: list[str], hunk: Hunk, added: set[int]) -> str | None:
    """The nearest existing ``def``/``class`` line that encloses the hunk, or None."""
    first = next((line for line in hunk.added if line.strip()), None)
    if first is None:
        return None
    target = _indent(first)
    for number in range(hunk.start - 1, 0, -1):
        line = head_lines[number - 1]
        if number in added or not line.strip() or _indent(line) >= target:
            continue
        if _SIGNATURE.match(line):
            return line.strip()
        target = _indent(line)
    return None


def _blame_subjects(repo: Path, since: str, path: str, hunk: Hunk) -> list[str]:
    """The subjects of the branch commits that added the hunk's lines, in order."""
    raw = _git.text(
        repo, "blame", "--porcelain", "-L", f"{hunk.start},+{len(hunk.added)}",
        f"{since}..HEAD", "--", path,
    )
    order: list[str] = []
    summaries: dict[str, str] = {}
    boundary_commits: set[str] = set()
    sha = ""
    for line in raw.splitlines():
        header = _BLAME_HEADER.match(line)
        if header:
            sha = header.group(1)
            if sha not in order:
                order.append(sha)
        elif line.startswith("summary "):
            summaries[sha] = line[len("summary "):]
        elif line == "boundary":
            boundary_commits.add(sha)
    return [summaries.get(s, s[:12]) for s in order if s not in boundary_commits]


def _fence(body: str) -> str:
    fence = "```"
    while fence in body:
        fence += "`"
    return fence


def _file_section(repo: Path, since: str, change: boundary.Change) -> str:
    if change.added is None:
        return f"## `{change.path}` (binary)\n\nA binary file; its contents are not listed.\n"
    out = [f"## `{change.path}` (+{change.added} -{change.removed})\n"]
    hunks = _hunks(repo, since, change.path)
    if not hunks:
        out.append("No added lines.\n")
        return "\n".join(out)
    head_lines = _git.run(repo, "show", f"HEAD:{change.path}").decode("utf-8", "replace")
    lines = head_lines.split("\n")
    added = {h.start + i for h in hunks for i in range(len(h.added))}
    for hunk in hunks:
        subjects = _blame_subjects(repo, since, change.path, hunk)
        by = "; ".join(f"`{s}`" for s in subjects) if subjects else "an unattributed commit"
        body_lines = []
        signature = _enclosing_signature(lines, hunk, added)
        if signature:
            body_lines.append(f"existing: {signature}")
        body_lines.extend(f"+{line}" for line in hunk.added)
        body = "\n".join(body_lines)
        fence = _fence(body)
        out.append(f"At line {hunk.start}, added by {by}:\n\n{fence}diff\n{body}\n{fence}\n")
    return "\n".join(out)


def build_index(repo: Path, base: str) -> str:
    """The full text of INTEGRATION.md for the branch's changes since ``merge-base(base, HEAD)``."""
    since = _git.merge_base(repo, base)
    outside = [c for c in boundary.branch_changes(repo, since) if boundary.is_outside(c.path)]
    if not outside:
        return f"{_INTRO}\n{_NOTHING}"
    sections = [_file_section(repo, since, change) for change in outside]
    return _INTRO + "\n" + "\n".join(sections)
